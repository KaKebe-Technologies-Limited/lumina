/**
 * Membership e-mails, built from the editable templates in Pages > Membership > E-mail templates (registry section "emails").
 * Plain text, header-injection safe (Mailer strips CR/LF), the applicant's name is reduced to a safe form because the message goes to an
 * address nobody has proven to own, and public sends are capped per address and per hour (the visitor still sees the normal success screen).
 * OWNER: architect (frozen). Nothing here logs personal data (ids / references only).
 *
 * Templates: ack (applicant after registering), staff (organisation), approved, rejected, payment, proof ("please upload a clearer proof of payment").
 * The CARD e-mail (cardIssued, with the PDF attached) takes its subject and text from the card settings (Admin > Membership > Membership card) and also has an
 * HTML version; the other messages are plain text from the registry (Pages > Membership > E-mail templates). All of them can use {dashboard_url}, the link to the
 * member's private page.
 */
final class MembershipMail
{
    public const TEMPLATES = ['ack', 'staff', 'approved', 'rejected', 'payment', 'proof'];

    /** Acknowledgement to the applicant. Returns true when handed to the mailer (or skipped by the send cap). */
    public static function applicationReceived(array $member): bool
    {
        if (!RateLimit::attempt('member-mail:' . sha1(strtolower((string) $member['email'])), 2, 86400) || !RateLimit::attempt('member-mail-all', 120, 3600)) {
            Log::warning('Membership e-mail skipped (send cap reached)', ['member' => $member['id'] ?? null]);
            return true;
        }
        return self::send('ack', $member);
    }

    /** Notification to the organisation (setting notify_email). Reply-to = the applicant. */
    public static function staffNotice(array $member): bool
    {
        try {
            [$subject, $body] = self::render('staff', $member);
            return Mailer::notify($subject, $body, (string) $member['email']);
        } catch (\Throwable $e) {
            Log::error('Membership staff notification failed: ' . $e->getMessage());
            return false;
        }
    }

    public static function approved(array $member): bool
    {
        return self::send('approved', $member);
    }

    public static function rejected(array $member): bool
    {
        return self::send('rejected', $member);
    }

    /** E-mail confirming a received payment (uses the receipt number of the payment row). */
    public static function paymentReceived(array $member, array $payment): bool
    {
        return self::send('payment', $member, ['payment' => $payment]);
    }

    /**
     * "Please upload a clearer proof of payment": a polite request with the link to the member's private page (template "proof"). Never throws.
     */
    public static function proofRejected(array $member): bool
    {
        return self::send('proof', $member);
    }

    /**
     * THE CARD E-MAIL: subject and text from the card settings (placeholders {name} {first_name} {site} {number} {type} {valid_until} {start_date} {dashboard_url}
     * {contact_email} {support_phone} {photo_note}), an HTML version with a button to the private page, the card as a PDF attachment (generated by the caller at send
     * time). Header-safe (the Mailer strips line breaks; the name is reduced to a safe form). Never throws. @return bool true when handed to the mailer
     */
    public static function cardIssued(array $member, string $pdf): bool
    {
        if ($pdf === '') {
            return false;
        }
        try {
            [$subject, $text, $html] = self::renderCard($member);
            $contact = MembershipService::contactEmail();
            $opts = ['html' => $html, 'attachments' => [['filename' => CardService::filename($member), 'content' => $pdf, 'type' => 'application/pdf']]];
            if ($contact !== '') {
                $opts['reply_to'] = $contact;
            }
            return Mailer::send((string) $member['email'], $subject, $text, $opts);
        } catch (\Throwable $e) {
            Log::error('Membership card e-mail failed: ' . $e->getMessage(), ['member' => $member['id'] ?? null]);
            return false;
        }
    }

    /**
     * The designer's TEST e-mail: the same message built from SAMPLE data (clearly marked) with the sample card attached. $override = unsaved designer values.
     * @param array<string,mixed> $override
     */
    public static function cardSample(string $to, string $pdf, array $override = []): bool
    {
        try {
            $sample = [
                'id' => 0, 'full_name' => 'Amina Akello', 'email' => $to, 'application_ref' => 'LAF-APP-2026-00000', 'type_name' => 'Individual Member', 'membership_number' => 'LAF-IND-26-0001',
                'start_date' => '2026-10-20', 'expiry_date' => '2027-10-19', 'photo_path' => null,
            ];
            [$subject, $text, $html] = self::renderCard($sample, $override, true);
            $opts = ['html' => $html, 'attachments' => [['filename' => 'Membership-card-SAMPLE.pdf', 'content' => $pdf, 'type' => 'application/pdf']]];
            return Mailer::send($to, '[TEST] ' . $subject, "THIS IS A TEST MESSAGE: the member, number and card are fictional.\n\n" . $text, $opts);
        } catch (\Throwable $e) {
            Log::error('Membership card test e-mail failed: ' . $e->getMessage());
            return false;
        }
    }

    /**
     * The card e-mail as [subject, plain text, HTML]. $override = unsaved card settings (designer preview); $sample = skip the dashboard link lookup.
     * @param array<string,mixed> $member @param array<string,mixed> $override @return array{0:string,1:string,2:string}
     */
    public static function renderCard(array $member, array $override = [], bool $sample = false): array
    {
        $s = CardSettings::resolve($override);
        // the message may have more lines than CardSettings::sanitise() keeps (6): an unsaved message is cleaned by CardPreview::cleanMessage()
        if (isset($override['membership_card_email_body']) && is_string($override['membership_card_email_body'])) {
            $own = CardPreview::cleanMessage($override['membership_card_email_body']);
            if ($own !== '') {
                $s['membership_card_email_body'] = $own;
            }
        }
        if ($sample) {                                                  // the fictional member of the reference card: valid from 20 Oct 2026, last valid day 19 Oct 2027
            $member['start_date'] = '2026-10-20';
            $member['expiry_date'] = '2027-10-20';
        }
        $vars = self::cardVars($member, $sample);
        $subject = trim((string) preg_replace('/\s+/', ' ', strtr($s['membership_card_email_subject'], $vars)));
        $text = trim((string) preg_replace("/\n{3,}/", "\n\n", strtr($s['membership_card_email_body'], $vars)));
        return [$subject, $text, self::cardHtml($s, $vars, $text)];
    }

    /** The colour darkened in small steps until $hex reaches 4.5:1 against $against (it stays as it is when it already does). */
    private static function readable(string $hex, string $against): string
    {
        $rgb = sscanf(ltrim($hex, '#'), '%02x%02x%02x');
        if (!is_array($rgb) || in_array(null, $rgb, true)) {
            return $hex;
        }
        for ($i = 0; $i < 30 && CardSettings::contrast(sprintf('#%02X%02X%02X', ...$rgb), $against) < 4.5; $i++) {
            $rgb = array_map(static fn(int $v): int => (int) floor($v * 0.94), $rgb);
        }
        return sprintf('#%02X%02X%02X', ...$rgb);
    }

    /**
     * The HTML version of the card e-mail: the SAME words as the plain text (the message from the designer), dressed in the card's colours. Table layout with inline styles
     * (mail programs ignore most CSS): a white header with the logo and the organisation, the paragraphs, a block of "Label: value" lines shown like the card's tiles, a button to the
     * member's private page (with the plain link under it for programs that hide buttons), and the support contact. Everything dynamic is escaped; only http(s) links become links.
     * @param array<string,string> $s resolved settings @param array<string,string> $vars cardVars() @param string $text the finished plain-text message
     */
    private static function cardHtml(array $s, array $vars, string $text): string
    {
        $c = CardSettings::colors($s);
        // the e-mail's small text and white-on-colour button must reach 4.5:1 (WCAG AA) even when the card's accent, gold or label colour (the owner's design) does not
        $accentText = self::readable($c['accent'], '#FFFFFF');
        $goldText = self::readable($c['gold'], '#FFFFFF');
        $labelText = self::readable($c['label'], $c['tile']);
        $esc = static fn(string $v): string => htmlspecialchars($v, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
        $url = (string) $vars['{dashboard_url}'];
        $link = static fn(string $h): string => (string) preg_replace('~(https?://[^\s<]+)~i', '<a href="$1" style="color:' . $accentText . ';word-break:break-all">$1</a>', $h);
        $font = "font-family:Arial,Helvetica,sans-serif;";
        $buttonLabel = MembershipService::copy('emails.card_button', 'Open my membership page');
        $button = $url !== ''
            ? '<table role="presentation" cellspacing="0" cellpadding="0" border="0" style="margin:6px 0 10px 0"><tr><td style="border-radius:6px;background:' . $accentText . '">'
                . '<a href="' . $esc($url) . '" style="display:inline-block;padding:13px 24px;' . $font . 'font-size:15px;font-weight:bold;color:#ffffff;text-decoration:none;border-radius:6px">' . $esc($buttonLabel) . '</a>'
                . '</td></tr></table>'
                . '<p style="margin:0 0 16px 0;' . $font . 'font-size:12px;line-height:1.5;color:' . $c['label'] . '">' . $link($esc($url)) . '</p>'
            : '';
        $buttonDone = false;
        $body = '';
        foreach (preg_split("/\n{2,}/", $text) ?: [] as $block) {
            $lines = array_values(array_filter(array_map('trim', explode("\n", $block)), static fn(string $l): bool => $l !== ''));
            if ($lines === []) {
                continue;
            }
            // "Name: Amina Akello / Member number: ..." -> a small details table, like the tiles of the card
            $isDetails = count($lines) >= 2;
            foreach ($lines as $l) {
                if (preg_match('/^[^:\n]{1,32}:\s+\S.*$/u', $l) !== 1 || preg_match('~^https?://~i', $l) === 1) {
                    $isDetails = false;
                    break;
                }
            }
            if ($isDetails) {
                $rows = '';
                foreach ($lines as $l) {
                    [$k, $v] = array_map('trim', explode(':', $l, 2));
                    $rows .= '<tr><td style="padding:7px 14px 7px 0;' . $font . 'font-size:11px;letter-spacing:.06em;text-transform:uppercase;color:' . $labelText . ';white-space:nowrap" valign="top">' . $esc($k) . '</td>'
                        . '<td style="padding:7px 0;' . $font . 'font-size:15px;font-weight:bold;color:' . $c['navy'] . '" valign="top">' . $esc($v) . '</td></tr>';
                }
                $body .= '<table role="presentation" cellspacing="0" cellpadding="0" border="0" width="100%" style="margin:4px 0 18px 0;background:' . $c['tile'] . ';border-radius:8px"><tr><td style="padding:10px 18px">'
                    . '<table role="presentation" cellspacing="0" cellpadding="0" border="0" width="100%">' . $rows . '</table></td></tr></table>';
                continue;
            }
            $hasUrl = $url !== '' && str_contains($block, $url);
            $shown = $hasUrl ? trim((string) preg_replace('/\s*' . preg_quote($url, '/') . '/', '', $block)) : $block;     // the button carries the link
            $html = $link(nl2br($esc($shown), false));
            $body .= '<p style="margin:0 0 14px 0;' . $font . 'font-size:15px;line-height:1.6;color:#1D1E20">' . $html . '</p>';
            if ($hasUrl && !$buttonDone) {
                $body .= $button;
                $buttonDone = true;
            }
        }
        if (!$buttonDone) {
            $body .= $button;
        }

        $logo = trim((string) ($s['membership_card_logo'] ?? ''));
        $logoUrl = '';
        if ($logo !== '') {
            $logoUrl = abs_url_for_image($logo);
        }
        if ($logoUrl === '' || preg_match('~^https?://~i', $logoUrl) !== 1) {
            $asset = asset('img/brand/logo-128.png');
            $logoUrl = preg_match('~^https?://~i', $asset) === 1 ? $asset : origin() . $asset;
        }
        $org = (string) $s['membership_card_org_name'];
        $tagline = (string) $s['membership_card_tagline'];
        $contact = [];
        if ((string) $vars['{support_phone}'] !== '') {
            $contact[] = $esc((string) $vars['{support_phone}']);
        }
        if ((string) $vars['{contact_email}'] !== '') {
            $contact[] = '<a href="mailto:' . $esc((string) $vars['{contact_email}']) . '" style="color:' . $c['muted'] . '">' . $esc((string) $vars['{contact_email}']) . '</a>';
        }
        $preheader = $esc(trim((string) preg_replace('/\s+/', ' ', mb_substr(strip_tags($text), 0, 110))));

        return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>' . $esc($org) . '</title></head>'
            . '<body style="margin:0;padding:0;background:' . $c['tile'] . '">'
            . '<div style="display:none;max-height:0;overflow:hidden;opacity:0;color:transparent">' . $preheader . '</div>'
            . '<table role="presentation" cellspacing="0" cellpadding="0" border="0" width="100%" style="background:' . $c['tile'] . '"><tr><td align="center" style="padding:24px 12px">'
            . '<table role="presentation" cellspacing="0" cellpadding="0" border="0" width="100%" style="max-width:600px;background:#ffffff;border-radius:10px;overflow:hidden">'
            . '<tr><td style="height:5px;line-height:5px;font-size:0;background:' . $c['accent'] . '">&nbsp;</td></tr>'
            . '<tr><td style="padding:20px 28px 16px 28px"><table role="presentation" cellspacing="0" cellpadding="0" border="0"><tr>'
            . '<td valign="middle" style="padding-right:14px"><img src="' . $esc($logoUrl) . '" width="48" height="48" alt="" style="display:block;border:0;border-radius:50%"></td>'
            . '<td valign="middle"><div style="' . $font . 'font-size:15px;font-weight:bold;letter-spacing:.03em;color:' . $c['navy'] . '">' . $esc($org) . '</div>'
            . ($tagline !== '' ? '<div style="' . $font . 'font-size:13px;font-style:italic;color:' . $goldText . '">' . $esc($tagline) . '</div>' : '')
            . '</td></tr></table></td></tr>'
            . '<tr><td style="padding:6px 28px 14px 28px">' . $body . '</td></tr>'
            . '<tr><td style="padding:14px 28px;background:' . $c['navy'] . ';' . $font . 'font-size:12px;line-height:1.6;color:' . $c['muted'] . '">'
            . $esc($org) . ($contact !== [] ? '<br>' . implode(' &middot; ', $contact) : '') . '</td></tr>'
            . '</table></td></tr></table></body></html>';
    }

    /** @param array<string,mixed> $member @return array<string,string> placeholder => value for the card e-mail */
    public static function cardVars(array $member, bool $sample = false): array
    {
        $base = self::vars($member);
        $phone = CardSettings::get('membership_card_support_phone');
        if ($phone === '') {
            $phone = Card\CardData::localPhone((string) setting('phone_1', ''));
        }
        $dash = $sample ? abs_url('membership/me/' . str_repeat('0', 64)) : (isset($member['id']) ? MembershipService::dashboardUrl($member) : '');
        $hasPhoto = !empty($member['photo_path']);
        return [
            '{name}'          => $base['{name}'],
            '{first_name}'    => $base['{first_name}'],
            '{site}'          => $base['{site}'],
            '{number}'        => $base['{membership_number}'],
            '{type}'          => $base['{type}'],
            '{valid_until}'   => !empty($member['expiry_date']) ? Card\CardData::date(MembershipService::lastValidDay((string) $member['expiry_date'])) : CardSettings::get('membership_card_no_expiry_text'),
            '{start_date}'    => !empty($member['start_date']) ? Card\CardData::date($member['start_date']) : '',
            '{dashboard_url}' => $dash,
            '{contact_email}' => $base['{contact_email}'],
            '{support_phone}' => $phone,
            '{photo_note}'    => $hasPhoto ? '' : MembershipService::copy('emails.card_photo_note', 'We do not have a photo of you yet, so your card shows your initials. Add a photo on your private page and we will send you a new card.') . "\n\n",
        ];
    }

    /**
     * Send one template to the member's address (staff "resend e-mail" uses this). $extra may carry 'payment' (row) for the payment template.
     * Never throws; returns false when the mailer refuses.
     */
    public static function send(string $template, array $member, array $extra = []): bool
    {
        if (!in_array($template, self::TEMPLATES, true) || $template === 'staff') {
            return false;
        }
        try {
            [$subject, $body] = self::render($template, $member, $extra);
            $contact = MembershipService::contactEmail();
            return Mailer::send((string) $member['email'], $subject, $body, $contact !== '' ? ['reply_to' => $contact] : []);
        } catch (\Throwable $e) {
            Log::error('Membership e-mail failed: ' . $e->getMessage(), ['template' => $template, 'member' => $member['id'] ?? null]);
            return false;
        }
    }

    /** @return array{0:string,1:string} [subject, body] with every placeholder filled in. */
    public static function render(string $template, array $member, array $extra = []): array
    {
        $vars = self::vars($member, $extra, $template);
        $subject = strtr(MembershipService::copy('emails.' . $template . '_subject'), $vars);
        $body = strtr(MembershipService::copy('emails.' . $template . '_body'), $vars);
        return [trim((string) preg_replace('/\s+/', ' ', $subject)), trim((string) preg_replace("/\n{3,}/", "\n\n", $body))];
    }

    /** @return array<string,string> placeholder => value */
    public static function vars(array $member, array $extra = [], string $template = ''): array
    {
        $payment = (array) ($extra['payment'] ?? []);
        $instructions = MembershipService::paymentInstructions();
        $name = (string) ($member['full_name'] ?? '');
        $first = self::safeName($name);
        $contact = MembershipService::contactEmail();
        $joining = MembershipService::joiningFeeLabel($member);
        $fee = MembershipService::memberFeeLabel($member);
        $amount = isset($payment['amount']) ? MembershipService::formatMoney($payment['amount'], (string) ($payment['currency'] ?? $member['fee_currency'])) : '';
        $methodList = MembershipService::options('payment_methods');
        $method = (string) ($payment['method'] ?? '');
        return [
            '{name}'                 => self::safeName($name, true),
            '{first_name}'           => $first,
            '{site}'                 => (string) setting('site_name', ''),
            '{ref}'                  => (string) ($member['application_ref'] ?? ''),
            '{type}'                 => (string) ($member['type_name'] ?? ''),
            '{fee}'                  => $fee . ($joining !== '' ? ' (' . $joining . ')' : ''),
            '{joining_fee}'          => $joining,
            '{payment_instructions}' => $instructions !== '' ? $instructions : MembershipService::copy('confirmation.payment_none'),
            '{contact_email}'        => $contact,
            '{url}'                  => abs_url('admin/members/' . (int) ($member['id'] ?? 0)),
            '{status_url}'           => isset($member['application_ref']) ? MembershipService::confirmationUrl((string) $member['application_ref']) : '',
            '{membership_number}'    => (string) ($member['membership_number'] ?? ''),
            '{start_date}'           => !empty($member['start_date']) ? format_date($member['start_date']) : '',
            '{expiry_date}'          => !empty($member['expiry_date']) ? format_date($member['expiry_date']) : MembershipService::copy('emails.no_expiry', 'No expiry'),
            '{renewal_due}'          => !empty($member['expiry_date']) ? format_date($member['expiry_date']) : MembershipService::copy('emails.no_renewal', 'None, this membership does not expire'),
            '{receipt}'              => (string) ($payment['receipt_number'] ?? ''),
            '{amount}'               => $amount,
            '{method}'               => $method !== '' ? ($methodList[$method] ?? label_from($method)) : '',
            '{dashboard_url}'        => !empty($member['id']) && $template !== 'staff' ? MembershipService::dashboardUrl($member) : '',
        ];
    }

    /**
     * A name that is safe inside a message sent to a third party's inbox: letters, digits and a few punctuation marks only (no links, no
     * line breaks), shortened. $full = whole name, otherwise the first word only. Empty -> the editable fallback word.
     */
    private static function safeName(string $name, bool $full = false): string
    {
        $n = (string) preg_replace('~(?:https?://|www\.)\S*~iu', ' ', $name);
        $n = (string) preg_replace('/[^\p{L}\p{M}\p{N} \'.-]+/u', ' ', $n);
        $n = trim((string) preg_replace('/\s+/u', ' ', $n));
        if (!$full) {
            $n = explode(' ', $n)[0] ?? '';
        }
        $n = mb_substr($n, 0, 40);
        if (preg_match('/\p{L}/u', $n) !== 1) {
            return MembershipService::copy('emails.name_fallback', 'there');
        }
        return $n;
    }
}
