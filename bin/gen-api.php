<?php
/**
 * Regenerates the "API reference" block of docs/ARCHITECTURE.md from the real code (Reflection), so signatures never drift.
 *   /c/xampp/php/php.exe bin/gen-api.php --write      rewrite the block between the API-REFERENCE markers in docs/ARCHITECTURE.md
 *   /c/xampp/php/php.exe bin/gen-api.php              print it
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit('CLI only.');
}
require dirname(__DIR__) . '/app/bootstrap.php';

function typeName(?ReflectionType $t): string
{
    if ($t === null) {
        return '';
    }
    $s = (string) $t;
    return str_replace('App\\Core\\', '', str_replace('App\\Models\\', '', $s));
}

function sig(ReflectionMethod $m): string
{
    $params = [];
    foreach ($m->getParameters() as $p) {
        $s = '';
        if ($p->getType() !== null) {
            $s .= typeName($p->getType()) . ' ';
        }
        if ($p->isVariadic()) {
            $s .= '...';
        }
        $s .= '$' . $p->getName();
        if ($p->isDefaultValueAvailable()) {
            $d = $p->getDefaultValue();
            $s .= ' = ' . (is_array($d) ? '[]' : (is_string($d) ? "'" . $d . "'" : var_export($d, true)));
            $s = str_replace('NULL', 'null', $s);
        }
        $params[] = $s;
    }
    $ret = $m->hasReturnType() ? ': ' . typeName($m->getReturnType()) : '';
    $prefix = $m->isStatic() ? '::' : '->';
    return $prefix . $m->getName() . '(' . implode(', ', $params) . ')' . $ret;
}

function firstDoc(ReflectionMethod $m): string
{
    $doc = $m->getDocComment();
    if (!$doc) {
        return '';
    }
    foreach (preg_split('/\R/', $doc) ?: [] as $line) {
        $line = trim(preg_replace('~\s*\*/\s*$~', '', preg_replace('~^\s*(/\*\*|\*)\s?~', '', $line) ?? '') ?? '');
        if ($line !== '' && $line[0] !== '@' && $line !== '/') {
            return $line;
        }
    }
    return '';
}

$out = "<!-- API-REFERENCE:START (generated by bin/gen-api.php - do not edit by hand) -->\n\n";

$out .= "### Core classes (namespace `App\\Core`, folder `app/core/`)\n\n";
$files = glob(APP_PATH . '/core/*.php') ?: [];
sort($files);
foreach ($files as $f) {
    $name = basename($f, '.php');
    $fq = 'App\\Core\\' . $name;
    if (!class_exists($fq)) {
        continue;
    }
    $r = new ReflectionClass($fq);
    $kind = $r->isAbstract() ? 'abstract class' : 'class';
    $ext = $r->getParentClass() ? ' extends `' . $r->getParentClass()->getShortName() . '`' : '';
    $out .= "#### `{$name}` ({$kind}{$ext})\n\n";
    $visibility = $r->isAbstract() ? (ReflectionMethod::IS_PUBLIC | ReflectionMethod::IS_PROTECTED) : ReflectionMethod::IS_PUBLIC;
    $methods = array_filter($r->getMethods($visibility), static fn(ReflectionMethod $m) => $m->getDeclaringClass()->getName() === $fq && !$m->isConstructor() || ($m->isConstructor() && $m->getDeclaringClass()->getName() === $fq && $m->getNumberOfParameters() > 0 && $name === 'Request'));
    foreach ($r->getReflectionConstants(ReflectionClassConstant::IS_PUBLIC) as $c) {
        $v = $c->getValue();
        $out .= '- const `' . $c->getName() . '`' . (is_scalar($v) ? ' = `' . var_export($v, true) . '`' : '') . "\n";
    }
    foreach ($methods as $m) {
        if ($m->getName() === '__construct' && $name !== 'Controller' && $name !== 'Request') {
            continue;
        }
        $d = firstDoc($m);
        $out .= '- ' . ($m->isProtected() ? '(protected) ' : '') . '`' . $name . sig($m) . '`' . ($d !== '' ? ' - ' . $d : '') . "\n";
    }
    $out .= "\n";
}

$out .= "### Models (namespace `App\\Models`, folder `app/models/`) - every model also has the generic `Model` API above\n\n";
$out .= "| Model | Table | Default order | Extra members |\n|---|---|---|---|\n";
$files = glob(APP_PATH . '/models/*.php') ?: [];
sort($files);
foreach ($files as $f) {
    $name = basename($f, '.php');
    $fq = 'App\\Models\\' . $name;
    $r = new ReflectionClass($fq);
    $extras = [];
    foreach ($r->getReflectionConstants() as $c) {
        $extras[] = 'const ' . $c->getName();
    }
    foreach ($r->getMethods(ReflectionMethod::IS_PUBLIC) as $m) {
        if ($m->getDeclaringClass()->getName() === $fq) {
            $extras[] = $name . sig($m);
        }
    }
    $table = $fq::table();
    $prop = $r->getParentClass()->getProperty('order');
    $prop->setAccessible(true);
    $order = (new ReflectionProperty($fq, 'order'))->getValue();
    $out .= "| `{$name}` | `{$table}` | `{$order}` | " . ($extras ? '`' . implode('`<br>`', $extras) . '`' : '-') . " |\n";
}

$out .= "\n### Global helper functions (`app/helpers.php`)\n\n";
$src = (string) file_get_contents(APP_PATH . '/helpers.php');
preg_match_all('~/\*\*(.*?)\*/\s*function\s+(\w+)\s*\(([^)]*)\)\s*:\s*([^\n{]+)~s', $src, $m, PREG_SET_ORDER);
foreach ($m as $hit) {
    $doc = '';
    foreach (preg_split('/\R/', $hit[1]) ?: [] as $line) {
        $line = trim(preg_replace('~^\s*\*\s?~', '', $line) ?? '');
        if ($line !== '' && $line[0] !== '@') {
            $doc = $line;
            break;
        }
    }
    $out .= '- `' . $hit[2] . '(' . trim(preg_replace('/\s+/', ' ', $hit[3]) ?? '') . '): ' . trim($hit[4]) . '`' . ($doc !== '' ? ' - ' . $doc : '') . "\n";
}
preg_match_all('~\nfunction\s+(\w+)\s*\(([^)]*)\)\s*:\s*([^\n{]+)~', $src, $all, PREG_SET_ORDER);
$documented = array_column($m, 2);
foreach ($all as $hit) {
    if (!in_array($hit[1], $documented, true)) {
        $out .= '- `' . $hit[1] . '(' . trim(preg_replace('/\s+/', ' ', $hit[2]) ?? '') . '): ' . trim($hit[3]) . '`' . "\n";
    }
}
$out .= "\n<!-- API-REFERENCE:END -->";

if (in_array('--write', $argv, true)) {
    $file = BASE_PATH . '/docs/ARCHITECTURE.md';
    $doc = (string) file_get_contents($file);
    $new = preg_replace('~<!-- API-REFERENCE:START.*?<!-- API-REFERENCE:END -->~s', str_replace('\\', '\\\\', str_replace('$', '\\$', $out)), $doc, 1, $count);
    if ($count !== 1) {
        fwrite(STDERR, "Markers not found in docs/ARCHITECTURE.md\n");
        exit(1);
    }
    file_put_contents($file, $new);
    echo "docs/ARCHITECTURE.md API reference updated (" . strlen($out) . " bytes).\n";
} else {
    echo $out . "\n";
}
