"""
Regenerates app/services/Membership/Card/CoreFontMetrics.php: advance widths (1000 units per em) of the PDF core fonts used by the
membership card, for every WinAnsi (Windows-1252) code 32..255. The numbers come from the Adobe AFM metrics bundled with ReportLab.
Only needed if a font is added. Run (needs `pip install reportlab`):
    python bin/dev/gen-card-font-metrics.py > app/services/Membership/Card/CoreFontMetrics.php
"""
from reportlab.pdfbase.pdfmetrics import stringWidth

FONTS = [
    ('helvetica',      'Helvetica'),
    ('helvetica-bold', 'Helvetica-Bold'),
    ('times-bold',     'Times-Bold'),
    ('times-italic',   'Times-Italic'),
    ('times-roman',    'Times-Roman'),
]

def char_for(code):
    try:
        return bytes([code]).decode('cp1252')
    except UnicodeDecodeError:
        return '•'          # undefined WinAnsi codes print as a bullet (PDF reference)

print("<?php")
print("declare(strict_types=1);")
print()
print("namespace App" + chr(92) + "Services" + chr(92) + "Membership" + chr(92) + "Card;")
print()
print("/**")
print(" * GENERATED by bin/dev/gen-card-font-metrics.py: do not edit by hand.")
print(" * Advance widths (units of 1/1000 em) of the PDF core fonts for WinAnsi codes 32..255 (index = code - 32). Source: Adobe AFM metrics (via ReportLab).")
print(" */")
print("final class CoreFontMetrics")
print("{")
print("    public const WIDTHS = [")
for key, name in FONTS:
    ws = [int(round(stringWidth(char_for(c), name, 1000))) for c in range(32, 256)]
    rows = []
    for i in range(0, len(ws), 16):
        rows.append("            " + ", ".join(str(w) for w in ws[i:i+16]) + ",")
    print("        '%s' => [" % key)
    print("\n".join(rows))
    print("        ],")
print("    ];")
print("}")
