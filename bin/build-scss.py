#!/usr/bin/env python
"""
Compile the SCSS bundles with libsass (Python module "sass").

    "/c/Users/SANTOS JR/AppData/Local/Python/bin/python.exe" bin/build-scss.py           # build once
    "/c/Users/SANTOS JR/AppData/Local/Python/bin/python.exe" bin/build-scss.py --watch   # rebuild when any .scss changes (polling, Ctrl+C to stop)

(Plain `python` on this PATH is Inkscape's interpreter and has NO sass module - always use the full path above.)

    scss/main.scss  -> assets/css/main.css   + assets/css/main.min.css    (public site)
    scss/admin.scss -> assets/css/admin.css  + assets/css/admin.min.css   (admin)

libsass 3.6 supports only @import (no @use/@forward, no sass:math). Exit code 1 on a compile error (watch mode keeps running).
"""
import sys
import time
from pathlib import Path

try:
    import sass
except ImportError:  # pragma: no cover
    sys.stderr.write('The "sass" module is missing. Use the Python at /c/Users/SANTOS JR/AppData/Local/Python/bin/python.exe\n')
    sys.exit(2)

ROOT = Path(__file__).resolve().parent.parent
SCSS = ROOT / 'scss'
OUT = ROOT / 'assets' / 'css'
BUNDLES = [('main.scss', 'main'), ('admin.scss', 'admin')]
BANNER = '/* Generated by bin/build-scss.py from scss/{src} - DO NOT EDIT, edit the .scss partials and rebuild. */\n'


def build_one(src_name: str, base: str) -> bool:
    src = SCSS / src_name
    if not src.exists():
        print('skip   %s (missing)' % src_name)
        return True
    try:
        expanded = sass.compile(filename=str(src), output_style='expanded', include_paths=[str(SCSS)])
        compressed = sass.compile(filename=str(src), output_style='compressed', include_paths=[str(SCSS)])
    except sass.CompileError as exc:
        sys.stderr.write('SCSS ERROR in %s:\n%s\n' % (src_name, exc))
        return False
    # libsass prepends a UTF-8 BOM to compressed output when the CSS contains non-ASCII characters; after the banner comment the BOM
    # would become part of the first selector and silently drop the first rule (:root with the custom properties). Remove it.
    expanded = expanded.lstrip('\ufeff')
    compressed = compressed.lstrip('\ufeff')
    OUT.mkdir(parents=True, exist_ok=True)
    banner = BANNER.format(src=src_name)
    (OUT / (base + '.css')).write_text(banner + expanded, encoding='utf-8', newline='\n')
    (OUT / (base + '.min.css')).write_text(banner + compressed, encoding='utf-8', newline='\n')
    print('built  assets/css/%s.css (%d KB) + %s.min.css (%d KB)' % (base, len(expanded) // 1024, base, len(compressed) // 1024))
    return True


def build_all() -> bool:
    ok = True
    for src_name, base in BUNDLES:
        ok = build_one(src_name, base) and ok
    return ok


def snapshot() -> dict:
    return {str(p): p.stat().st_mtime for p in SCSS.rglob('*.scss')}


def main() -> int:
    if '--watch' not in sys.argv:
        return 0 if build_all() else 1
    print('Watching scss/ (poll every 1s). Ctrl+C to stop.')
    build_all()
    last = snapshot()
    try:
        while True:
            time.sleep(1)
            now = snapshot()
            if now != last:
                last = now
                print('-- change detected', time.strftime('%H:%M:%S'))
                build_all()
    except KeyboardInterrupt:
        print('stopped')
    return 0


if __name__ == '__main__':
    sys.exit(main())
