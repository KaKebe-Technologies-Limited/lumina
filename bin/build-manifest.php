<?php
/**
 * Writes app/config/manifest.php: the list of every site file (app/**, assets/css, assets/js) with a fingerprint of its text, so Admin > Administration > File check
 * can tell, on the LIVE site, which files are missing or are an older version than the ones in the project. Run it before packaging an upload, and upload the new manifest too:
 *
 *   /c/xampp/php/php.exe bin/build-manifest.php
 *
 * The fingerprint ignores line endings (CRLF / LF), so a file copied from Windows still matches.
 */
declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit('CLI only.');
}
$root = dirname(__DIR__);
$files = [];
$scan = static function (string $dir, array $ext) use ($root, &$files, &$scan): void {
    foreach (scandir($root . '/' . $dir) ?: [] as $f) {
        if ($f === '.' || $f === '..') {
            continue;
        }
        $rel = $dir . '/' . $f;
        if (is_dir($root . '/' . $rel)) {
            $scan($rel, $ext);
        } elseif (in_array(strtolower(pathinfo($f, PATHINFO_EXTENSION)), $ext, true)) {
            $files[$rel] = sha1(str_replace("\r\n", "\n", (string) file_get_contents($root . '/' . $rel)));
        }
    }
};
$scan('app', ['php', 'js', 'txt']);
$scan('assets/css', ['css']);
$scan('assets/js', ['js']);
unset($files['app/config/manifest.php']);                         // the manifest cannot fingerprint itself
ksort($files);
$out = "<?php\n// GENERATED by bin/build-manifest.php - do not edit. Used by Admin > Administration > File check.\nreturn " . var_export(['generated' => date('Y-m-d H:i'), 'files' => $files], true) . ";\n";
file_put_contents($root . '/app/config/manifest.php', $out);
echo count($files) . " files listed in app/config/manifest.php\n";
